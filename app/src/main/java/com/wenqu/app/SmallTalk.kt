    fun match(raw: String): String? {
        val q = raw.trim()
        for (r in rules) {
            if (r.re.matches(q)) {
                val reply = pick(r.replies)
                return reply
            }
        }
        // 轻量情绪兜底：特别短又没有信息量的输入
        if (q.length <= 3 && Regex("^[\\u4e00-\\u9fff～~。.!?！？\\s]+$").matches(q) &&
            !Regex("查|搜|是什么|吗|怎么|多少|几").containsMatchIn(q)
        ) {
            return pick(listOf(
                "嗯？想聊点什么，还是有问题要我查？说具体点我就能开工。",
                "我在听。你要是给个具体问题，我立刻去全网翻答案。"
            ))
        }
        return null
    }

    fun gameStart(): String {
        val target = Random.nextInt(1, 101)
        lastReply = ""
        return "__GUESS_INIT__:$target"
    }

    fun guessReply(target: Int, guess: Int, tries: Int): String {
        val persona = listOf(
            "小渠把结果翻过来一看：", "我查遍了全网没有答案，因为答案在你手里：", "答案出炉："
        )
        return when {
            guess < target -> "${persona.random()}你说的 $guess 小了，往上猜。目前已经猜了 $tries 次。"
            guess > target -> "${persona.random()}你说的 $guess 大了，往下压一压。目前 $tries 次了，稳住。"
            else -> "__GUESS_WIN__:$tries"
        }
    }

